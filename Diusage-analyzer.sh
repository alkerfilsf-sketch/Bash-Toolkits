echo "|$============================================================================$/ DISK USAGE ANALYZER \$====================================================================$|"
echo " "
echo " "
echo "==========================================================================="
echo "}~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~{"
i=0
while true
do
     echo " "
     read -p "Silahkan Masukkan Nama Folder: " File[$i]
     echo " "
     read -p "Mau lanjut? (ya/tidak): " lanjut
     echo " "
     if [ "$lanjut" = "tidak" ]; then
     break
     fi

   ((i++))
done
echo "}~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~{"
echo "==========================================================================="
echo " "
echo "File sedang dicari, Harap tunggu...."
echo " "
for ((i=0; i<${#File[@]}; i++))
do
    found[$i]=$(find ~ -name "${File[$i]}" -type d -print -quit)

    if [ -n "${found[$i]}" ]; then
        hasil[$i]=$(du -sh "${found[$i]}" | cut -f1)
    else
        echo "File ${File[$i]} tidak ditemukan"
    fi
done
    echo "=================================================================================================================================================================="
    echo "==================================================================$ Hasil Disk Usage Analyzer $===================================================================="
    echo "==================================================================================================================================================================="
for ((i=0; i<${#File[@]}; i++))
do
    echo " "
    echo "File : (${found[$i]})"
    echo "Folder ${File[$i]} : (${hasil[$i]})"
    echo " "
done
    echo "=================================================================================================================================================================="
    echo "=================================================================================================================================================================="
printf 'Waktu pemeriksaan: %s\n' "$(date '+%d-%m-%Y %H:%M:%S %Z')"
